import { createPlaceholderImage } from "@/data/content-images";
import type { ContentImage } from "@/types/content";

export type AlphabetLetterCategory =
  | "nguyen-am-don"
  | "nguyen-am-ghep"
  | "phu-am"
  | "phu-am-ghep"
  | "thanh-dieu";

export interface AlphabetLetter {
  id: string;
  slug: string;
  category: AlphabetLetterCategory;
  displayLabel?: string;
  ipa: string;
  lowercaseWritingForm: string;
  lowercaseForm: string;
  uppercaseForm: string;
  uppercaseWritingForm: string;
  image: ContentImage;
}

type AlphabetLetterSeed = Omit<AlphabetLetter, "id" | "image"> & {
  image?: ContentImage;
  imageCaption?: string;
};

function createAlphabetLetter(seed: AlphabetLetterSeed): AlphabetLetter {
  const placeholderSubject =
    seed.displayLabel?.toLowerCase() ?? `chữ ${seed.uppercaseForm}`;

  return {
    ...seed,
    id: seed.slug,
    image:
      seed.image ??
      createPlaceholderImage(
        seed.slug,
        `Minh họa ${placeholderSubject}`,
        seed.imageCaption ??
          `Vị trí minh họa cho ${placeholderSubject} đang chờ bổ sung hình ảnh.`,
        "Bảng chữ cái",
        seed.slug,
        "minh họa",
      ),
  };
}

