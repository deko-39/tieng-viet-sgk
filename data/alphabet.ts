import { createPlaceholderImage } from "@/data/content-images";
import type { ContentImage } from "@/types/content";

export type AlphabetLetterCategory =
  | "nguyen-am-don"
  | "nguyen-am-doi"
  | "phu-am"
  | "thanh-dieu";

export interface AlphabetLetter {
  slug: string;
  category: AlphabetLetterCategory;
  ipa: string;
  lowercaseWritingForm: string;
  lowercaseForm: string;
  uppercaseForm: string;
  uppercaseWritingForm: string;
  image: ContentImage;
}

type AlphabetLetterSeed = Omit<AlphabetLetter, "image"> & {
  image?: ContentImage;
  imageCaption?: string;
};

function createAlphabetLetter(seed: AlphabetLetterSeed): AlphabetLetter {
  return {
    ...seed,
    image:
      seed.image ??
      createPlaceholderImage(
        seed.slug,
        `Minh họa chữ ${seed.uppercaseForm}`,
        seed.imageCaption ??
          `Vị trí minh họa cho chữ ${seed.uppercaseForm} đang chờ bổ sung hình ảnh.`,
        "Bảng chữ cái",
        seed.slug,
        "minh họa",
      ),
  };
}

